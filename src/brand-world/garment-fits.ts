export function garmentLayout(fit: GarmentFit) {
  const xs = fit.outline.map(([x]) => x);
  const ys = fit.outline.map(([, y]) => y);
  const scale = Math.min(1.78 / (Math.max(...xs) - Math.min(...xs)), 1.97 / (Math.max(...ys) - Math.min(...ys)));
  return { scale, left: Math.min(...xs), top: Math.min(...ys), right: Math.max(...xs), bottom: Math.max(...ys) };
}
